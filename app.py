#!/usr/bin/env python3
"""
php2shell-scanner — web UI backend.

Thin FastAPI wrapper around the original assetnote scanner.py. The detection
engine is NOT reimplemented: we import scanner.check_vulnerability() and run it
in a thread pool, exactly like the original CLI's main() does.

Live visibility: scanner.send_post is monkeypatched (scanner.py stays
untouched) so every control/probe HTTP exchange emits a begin/end "activity"
event. Results and activity are interleaved to the browser over SSE, so the
user sees each probe fire in real time instead of a frozen "starting…".

Run:
    pip install -r requirements.txt
    python app.py              # -> http://127.0.0.1:8000
    python app.py --host 0.0.0.0 --port 8000
"""

import argparse
import asyncio
import json
import queue
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import List, Optional

import uvicorn
from fastapi import FastAPI
from fastapi.responses import HTMLResponse, JSONResponse, StreamingResponse
from pydantic import BaseModel

import scanner  # vendored, unmodified

APP_DIR = Path(__file__).resolve().parent
INDEX_HTML = APP_DIR / "index.html"

MAX_THREADS = 50  # sane upper bound; the engine sends ~29 MiB per probed path

app = FastAPI(title="php2shell-scanner web", docs_url=None, redoc_url=None)

# --- live activity instrumentation -----------------------------------------
# Each worker thread sets _tls.emit to the active run's push function. The
# monkeypatched send_post (running in that same thread) calls it around every
# HTTP exchange. One scan at a time is the normal local-tool case.
_tls = threading.local()
_orig_send_post = scanner.send_post


def _patched_send_post(target_url, body, boundary, custom_headers, timeout, verify_ssl):
    emit = getattr(_tls, "emit", None)
    if emit is None:
        return _orig_send_post(
            target_url, body, boundary, custom_headers, timeout, verify_ssl
        )
    is_control = boundary == scanner.CONTROL_BOUNDARY and body == scanner.CONTROL_BODY
    size = len(body)
    if is_control:
        phase, label = "control", "control"
    else:
        phase, label = "probe", f"{round(size / (1 << 20))} MiB"
    emit({"t": "begin", "phase": phase, "label": label, "url": target_url, "bytes": size})
    started = time.monotonic()
    resp = _orig_send_post(
        target_url, body, boundary, custom_headers, timeout, verify_ssl
    )
    waf_vendor, waf_sig = _waf_from_response(resp)
    emit({
        "t": "end", "phase": phase, "label": label, "url": target_url,
        "bytes": size, "sent": getattr(resp, "bytes_sent", None),
        "status": getattr(resp, "status_code", None),
        "error": getattr(resp, "error", None),
        "ms": round((time.monotonic() - started) * 1000),
        "waf": waf_vendor, "waf_sig": waf_sig,
    })
    return resp


scanner.send_post = _patched_send_post
# ---------------------------------------------------------------------------


class ScanRequest(BaseModel):
    hosts: List[str] = []
    threads: int = 10
    timeout: int = 60
    sapi: str = "auto"
    headers: List[str] = []       # ["Key: Value", ...]
    insecure: bool = False
    paths: Optional[List[str]] = None


# --- WAF / block-page detection --------------------------------------------
# A 200 can actually be a WAF block page (e.g. F5 ASM support-ID page). Flag it
# so the operator is not fooled into reading a false NO SIGNAL. This only
# annotates the result; scanner.py's verdict is untouched. Conservative needles,
# matched case-insensitively against the response dump (headers + body) + reason.
WAF_SIGNATURES = [
    ("F5 BIG-IP ASM", ["your support id is", "support id:", "the requested url was rejected", "server: bigip"]),
    ("Imperva/Incapsula", ["_incapsula_resource", "incapsula incident", "incident id", "x-iinfo", "x-cdn: incapsula"]),
    ("Akamai", ["akamaighost", "reference #", "errors.edgesuite.net", "akamai error"]),
    ("Cloudflare challenge", ["attention required", "just a moment", "cf-chl", "challenge-platform", "cdn-cgi/challenge", "error 1020"]),
    ("AWS WAF", ["x-amzn-waf", "aws waf", "request blocked"]),
    ("ModSecurity", ["mod_security", "generated by mod_security", "not acceptable"]),
    ("Generic WAF", ["request unsuccessful", "web application firewall", "access denied", "has been blocked", "blocked by"]),
]


def _waf_match(hay: str):
    if not hay:
        return (None, None)
    for vendor, needles in WAF_SIGNATURES:
        for needle in needles:
            if needle in hay:
                return (vendor, needle)
    return (None, None)


def _waf_from_response(resp) -> tuple:
    # Inspect the ACTUAL exchange (headers + first 8 KiB of body). Done per
    # exchange because scanner overwrites result["response"] each probe, so a
    # WAF 200 on the control/early probe would otherwise be lost when a later
    # probe times out.
    try:
        parts = [f"{k}: {v}" for k, v in (getattr(resp, "headers", None) or {}).items()]
        body = getattr(resp, "body", b"") or b""
        parts.append(body[:8192].decode("latin-1", "ignore"))
        return _waf_match("\n".join(parts).lower())
    except Exception:  # noqa: BLE001
        return (None, None)


def detect_waf(result: dict) -> None:
    # Fallback: scan the final retained response + reason (used only when no
    # per-exchange WAF hit was recorded).
    vendor, needle = _waf_match(
        " ".join(filter(None, [result.get("response") or "", result.get("reason") or ""])).lower()
    )
    result["waf_blocked"] = bool(vendor)
    result["waf_vendor"] = vendor
    result["waf_signature"] = needle
# ---------------------------------------------------------------------------


def _sse(event: str, data: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(data, default=str)}\n\n"


@app.get("/", response_class=HTMLResponse)
def index() -> str:
    return INDEX_HTML.read_text(encoding="utf-8")


@app.get("/api/health")
def health() -> dict:
    return {"ok": True, "cves": scanner.CVES}


@app.post("/api/scan")
async def scan(req: ScanRequest):
    try:
        custom_headers = scanner.parse_headers(req.headers)
    except ValueError as exc:
        return JSONResponse({"error": str(exc)}, status_code=400)

    hosts = scanner.deduplicate_hosts([h.strip() for h in req.hosts if h.strip()])
    if not hosts:
        return JSONResponse({"error": "No hosts to scan"}, status_code=400)

    paths = [p.strip() for p in (req.paths or []) if p.strip()] or None
    sapi = req.sapi if req.sapi in ("auto", "mod_php", "fpm") else "auto"
    threads = max(1, min(int(req.threads or 10), MAX_THREADS))
    timeout = max(1, int(req.timeout or 60))
    verify_ssl = not req.insecure

    activity: "queue.Queue[dict]" = queue.Queue()

    def run_one(host: str) -> dict:
        # Route this thread's probe activity into the shared run queue, tagged
        # with the host, and remember the first WAF hit seen on ANY exchange.
        waf_hit: dict = {}

        def emit(ev: dict) -> None:
            ev = dict(ev)
            ev["host"] = scanner.safe_url_label(host)
            if ev.get("t") == "end" and ev.get("waf") and not waf_hit:
                waf_hit["vendor"] = ev["waf"]
                waf_hit["sig"] = ev.get("waf_sig")
            activity.put(ev)
        _tls.emit = emit
        try:
            result = scanner.check_vulnerability(
                host,
                timeout=timeout,
                verify_ssl=verify_ssl,
                custom_headers=custom_headers,
                sapi=sapi,
                paths=paths,
            )
        except Exception as exc:  # noqa: BLE001
            result = scanner.base_result(scanner.safe_url_label(host))
            result["error"] = f"unexpected error: {exc}"
            result["reason"] = result["error"]
        finally:
            _tls.emit = None
        if waf_hit:
            result["waf_blocked"] = True
            result["waf_vendor"] = waf_hit["vendor"]
            result["waf_signature"] = waf_hit["sig"]
        else:
            detect_waf(result)
        return result

    async def event_stream():
        loop = asyncio.get_event_loop()
        yield _sse("meta", {"total": len(hosts), "threads": threads, "sapi": sapi})
        executor = ThreadPoolExecutor(max_workers=threads)
        try:
            pending = {loop.run_in_executor(executor, run_one, h) for h in hosts}
            done = 0
            while pending or not activity.empty():
                # Drain live probe activity first so it stays real-time.
                while True:
                    try:
                        yield _sse("activity", activity.get_nowait())
                    except queue.Empty:
                        break
                if pending:
                    finished, pending = await asyncio.wait(
                        pending, timeout=0.15, return_when=asyncio.FIRST_COMPLETED
                    )
                    for fut in finished:
                        done += 1
                        yield _sse("result", {"done": done, "total": len(hosts), "result": fut.result()})
                else:
                    await asyncio.sleep(0.03)
        finally:
            executor.shutdown(wait=False)
        yield _sse("done", {"total": len(hosts)})

    return StreamingResponse(
        event_stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


def parse_args():
    ap = argparse.ArgumentParser(description="php2shell-scanner web UI")
    ap.add_argument("--host", default="127.0.0.1", help="bind address (default: 127.0.0.1)")
    ap.add_argument("--port", type=int, default=8000, help="port (default: 8000)")
    return ap.parse_args()


if __name__ == "__main__":
    args = parse_args()
    print(f"php2shell-scanner web  ->  http://{args.host}:{args.port}")
    print(f"engine: {scanner.CVES}")
    uvicorn.run(app, host=args.host, port=args.port, log_level="info")
